from pyspark.sql import SparkSession
from pyspark.sql.functions import col, length, trim

print("Libraries imported successfully!")

spark = SparkSession.builder \
    .appName("Movie Review Analysis") \
    .getOrCreate()

print("Spark session created successfully!")

from google.colab import files

uploaded = files.upload()

df = spark.read.csv(
    "IMDB Dataset.csv",
    header=True,
    inferSchema=True
)

print("Dataset loaded successfully!")

df.printSchema()

df.show(5, truncate=False)

cleaned_df = df.filter(
    col("review").isNotNull() &
    (trim(col("review")) != "")
)

print("Data cleaning completed!")

print("Original number of reviews:", df.count())

print("Number of reviews after cleaning:", cleaned_df.count())

total_reviews = cleaned_df.count()

print("Total number of reviews:", total_reviews)

cleaned_df.groupBy("sentiment").count().show()

df = spark.read.csv(
    "IMDB Dataset.csv",
    header=True,
    inferSchema=True,
    multiLine=True,
    escape='"'
)

print("Dataset reloaded successfully!")

df.printSchema()

df.show(5, truncate=False)

cleaned_df = df.filter(
    col("review").isNotNull() &
    (trim(col("review")) != "")
)

print("Data cleaning completed!")

cleaned_df.groupBy("sentiment").count().show()

transformed_df = cleaned_df.withColumn(
    "review_length",
    length(col("review"))
)

print("Review length column created successfully!")

transformed_df.select(
    "review",
    "sentiment",
    "review_length"
).show(5, truncate=False)

long_reviews = transformed_df.filter(
    col("review_length") > 500
)

long_reviews.show(10, truncate=False)

print(
    "Number of reviews longer than 500 characters:",
    long_reviews.count()
)

transformed_df.coalesce(1).write \
    .mode("overwrite") \
    .option("header", True) \
    .csv("/content/cleaned_movie_reviews")

print("Dataset saved successfully!")

